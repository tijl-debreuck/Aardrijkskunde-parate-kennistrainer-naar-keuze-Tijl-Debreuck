// Auto-populate reverse lookup from geoTranslations (Dutch -> English)
Object.entries(geoTranslations).forEach(([nl, en]) => {
  reverseGeoTranslations[en] = nl;
  reverseGeoTranslations[en.toLowerCase()] = nl;
});

/**
 * Translates a given name according to the target language.
 */
export function translateName(name: string | null | undefined, lang: Language): string {
  if (!name) return '';
  if (lang === 'nl') {
    return reverseGeoTranslations[name] || reverseGeoTranslations[name.toLowerCase()] || name;
  }
  return geoTranslations[name] || name;
}

